import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {validateCoveragePass,hostAllowed} from '../scripts/coverage-pass-lib.mjs';
const root=new URL('../',import.meta.url);
const pass=JSON.parse(fs.readFileSync(new URL('coverage-passes/dyson/jp-first-six-guide-indexes-20261106.json',root),'utf8'));
const gate=validateCoveragePass(pass);
assert.equal(gate.valid,true,gate.errors.join('; '));
assert.equal(gate.completionReady,true);
assert.equal(gate.summary.capturedPopulation,6);
assert.equal(gate.summary.unreviewedCount,0);
assert.deepEqual(gate.summary.states,{direct:6,shared:0,support_only:0,held:0});
assert.deepEqual(pass.reconciliation,{captured:6,direct:6,shared:0,support_only:0,held:0,public:6});
assert.equal(pass.universe.sourceObservation.githubLiveGateResult,'blocked_by_manufacturer_403_not_verified');
assert.equal(pass.universe.sourceObservation.pdfBytesFetched,false);
assert.equal(new Set(pass.universe.sourceUrls).size,5);
const ctx=vm.createContext({window:{},URL});
for(const f of ['data/manuals.coverage-passes.js','data/manuals.coverage-pass.dyson-jp-six-manual-index.js','affiliate-config.js'])vm.runInContext(fs.readFileSync(new URL(f,root),'utf8'),ctx,{filename:f});
assert.ok(Array.from(ctx.window.MANUALFINDER_COVERAGE_PASS_BATCHES).includes('manuals.coverage-pass.dyson-jp-six-manual-index.js'));
const rows=Array.from(ctx.window.MANUALFINDER_BUILD_COVERAGE_PASSES()).filter(x=>x.maker==='Dyson');
assert.equal(rows.length,6);
assert.deepEqual(new Set(rows.map(x=>x.model)),new Set(pass.universe.models));
assert.equal(new Set(rows.map(x=>x.id)).size,6);
const evidence=new Map(pass.records.map(x=>[x.model,x]));
const cfg=ctx.window.MANUALFINDER_AFFILIATE_CONFIG;
for(const row of rows){
 const e=evidence.get(row.model);assert.ok(e);
 assert.equal(e.state,'direct');
 assert.equal(e.manualUrl,row.manualUrl);
 assert.equal(row.supportUrl,row.manualUrl);
 assert.equal(row.brand,'Dyson');
 assert.equal(row.category,'家電');
 assert.equal(row.country,'Japan');
 assert.equal(row.manualKind,'manual-index');
 assert.equal(row.sharedTarget,false);
 assert.equal(row.resolutionState,'direct_manual_page');
 assert.equal(row.sourceType,'official');
 assert.equal(row.sourceLevel,'A');
 assert.equal(row.verifiedAt,'2026-11-06');
 assert.ok(hostAllowed(row.manualUrl,pass.allowedDomains));
 assert.equal(new URL(row.manualUrl).hostname,'www.dyson.co.jp');
 assert.ok(row.noteJa.includes('PDFへの直接リンクではありません'));
 assert.ok(row.linkReview.includes('HTTP403'));
 const u=new URL(cfg.buildModelSearchUrl(row));
 assert.equal(u.searchParams.get('tag'),'nicheworks09-22');
 assert.equal(u.searchParams.get('k'),'Dyson '+row.model);
 assert.equal(cfg.getConsumableOffers(row).length,0,'no inferred accessories');
}
assert.equal(rows.filter(x=>x.model.includes('(SV46)')||x.model.includes('(SV20)')).length,2);
for(const m of ['(SV46)','(SV20)'])assert.ok(rows.find(x=>x.model.includes(m)).noteJa.includes('別の説明書'));
const cov=fs.readFileSync(new URL('COVERAGE.md',root),'utf8');
assert.ok(cov.includes('**2,685 verified model/caliber rows**'));
assert.ok(cov.includes('| **Total** | **2,685** |'));
assert.ok(cov.includes('| Dyson | 6 | expanded, bounded |'));
assert.ok(cov.includes('| 26 | Dyson | **expanded — 6**'));
for(const f of ['index.html','en/index.html','app.paged.js'])assert.ok(fs.readFileSync(new URL(f,root),'utf8').includes('mf-dyson6-20261106a'),f);
console.log('Dyson JP six exact HTML official manual indexes, V12 SV variants separated, 403 transparently held from live verification PASS');
