import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {validateCoveragePass,hostAllowed} from '../scripts/coverage-pass-lib.mjs';
const root=new URL('../',import.meta.url);
const pass=JSON.parse(fs.readFileSync(new URL('coverage-passes/nec-lavie/jp-archived-exact18-manual-index-20261104.json',root),'utf8'));
const gate=validateCoveragePass(pass);
assert.equal(gate.valid,true,gate.errors.join('; '));
assert.equal(gate.completionReady,true);
assert.equal(gate.summary.capturedPopulation,18);
assert.equal(gate.summary.unreviewedCount,0);
assert.deepEqual(gate.summary.states,{direct:18,shared:0,support_only:0,held:0});
const ctx=vm.createContext({window:{},URL});
for(const f of ['data/manuals.coverage-passes.js','data/manuals.coverage-pass.nec-lavie-jp-exact18.js','affiliate-config.js'])vm.runInContext(fs.readFileSync(new URL(f,root),'utf8'),ctx,{filename:f});
assert.ok(Array.from(ctx.window.MANUALFINDER_COVERAGE_PASS_BATCHES).includes('manuals.coverage-pass.nec-lavie-jp-exact18.js'));
const rows=Array.from(ctx.window.MANUALFINDER_BUILD_COVERAGE_PASSES()).filter(x=>x.maker==='NEC LAVIE');
assert.equal(rows.length,18);
assert.equal(new Set(rows.map(x=>x.id)).size,18);
assert.deepEqual(new Set(rows.map(x=>x.model)),new Set(pass.universe.models));
assert.equal(rows.filter(x=>x.family.includes('Note Standard')).length,12);
assert.equal(rows.filter(x=>x.family.includes('LaVie S')).length,6);
const byModel=new Map(pass.records.map(x=>[x.model,x]));
const cfg=ctx.window.MANUALFINDER_AFFILIATE_CONFIG;
for(const row of rows){
 const record=byModel.get(row.model);assert.ok(record);
 assert.equal(row.sourceType,'official');assert.equal(row.sourceLevel,'A');
 assert.equal(row.manualKind,'manual-index');assert.equal(row.sharedTarget,false);
 assert.equal(row.manualUrl,record.manualUrl);assert.equal(row.evidenceUrl,record.manualUrl);
 assert.ok(hostAllowed(row.manualUrl,['nec-lavie.jp']));
 assert.equal(new URL(row.manualUrl).hostname,'support.nec-lavie.jp');
 assert.ok(row.noteJa.includes(record.standardModel));
 assert.ok(row.noteJa.includes('読み替え'));
 assert.ok(row.noteJa.includes('直接PDFではありません'));
 const search=new URL(cfg.buildModelSearchUrl(row));
 assert.equal(search.hostname,'www.amazon.co.jp');
 assert.equal(search.searchParams.get('tag'),'nicheworks09-22');
 assert.equal(search.searchParams.get('k'),'NEC LAVIE '+row.model);
 assert.equal(cfg.getConsumableOffers(row).length,0);
}
const cov=fs.readFileSync(new URL('COVERAGE.md',root),'utf8');
assert.ok(cov.includes('**2,685 verified model/caliber rows**'));
assert.ok(cov.includes('| **Total** | **2,685** |'));
assert.ok(cov.includes('| NEC LAVIE | 18 | expanded, bounded |'));
assert.ok(cov.includes('| 17 | NEC LAVIE | **expanded — 18**'));
for(const f of ['index.html','en/index.html','app.paged.js'])assert.ok(fs.readFileSync(new URL(f,root),'utf8').includes('mf-dyson6-20261106a'),f);
console.log('NEC 18 exact SKU official manuals indexes, base mapping, amendment notes and tagged searches PASS.');
