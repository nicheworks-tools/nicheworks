import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {validateCoveragePass,hostAllowed} from '../scripts/coverage-pass-lib.mjs';
const root=new URL('../',import.meta.url);
const pass=JSON.parse(fs.readFileSync(new URL('coverage-passes/oppo/jp-first-nine-mobile-guidepdf-20261105.json',root),'utf8'));
const audit=validateCoveragePass(pass);
assert.equal(audit.valid,true,audit.errors.join('; '));
assert.equal(audit.completionReady,true);
assert.equal(audit.summary.capturedPopulation,9);
assert.equal(audit.summary.unreviewedCount,0);
assert.deepEqual(audit.summary.states,{direct:7,shared:0,support_only:0,held:2});
assert.deepEqual(pass.reconciliation,{captured:9,direct:7,shared:0,support_only:0,held:2,public:7});
assert.deepEqual(new Set(pass.records.filter(r=>r.state==='held').map(r=>r.model)),new Set(['Reno A','Reno7 A']));
for(const r of pass.records.filter(r=>r.state==='held')){assert.ok(r.reason.includes('41879485312'));assert.ok(r.attemptedDiscovery.length>=2);}
const ctx=vm.createContext({window:{},URL});
for(const f of ['data/manuals.coverage-passes.js','data/manuals.coverage-pass.oppo-jp-seven-guides.js','affiliate-config.js'])vm.runInContext(fs.readFileSync(new URL(f,root),'utf8'),ctx,{filename:f});
assert.ok(Array.from(ctx.window.MANUALFINDER_COVERAGE_PASS_BATCHES).includes('manuals.coverage-pass.oppo-jp-seven-guides.js'));
const rows=Array.from(ctx.window.MANUALFINDER_BUILD_COVERAGE_PASSES()).filter(r=>r.maker==='OPPO');
assert.equal(rows.length,7);
assert.equal(new Set(rows.map(r=>r.id)).size,7);
assert.deepEqual(new Set(rows.map(r=>r.model)),new Set(pass.records.filter(r=>r.state==='direct').map(r=>r.model)));
const evidence=new Map(pass.records.map(r=>[r.model,r]));
const aff=ctx.window.MANUALFINDER_AFFILIATE_CONFIG;
for(const r of rows){
 const e=evidence.get(r.model);assert.ok(e);
 assert.equal(e.manualUrl,r.manualUrl);assert.equal(e.manualKind,r.manualKind);
 assert.equal(r.brand,'OPPO');assert.equal(r.category,'PC・スマホ');
 assert.equal(r.sourceType,'official');assert.equal(r.sourceLevel,'A');
 assert.equal(r.verifiedAt,'2026-11-05');assert.equal(r.sharedTarget,false);
 assert.equal(r.resolutionState,'direct_manual_page');assert.equal(r.evidenceUrl,r.manualUrl);
 assert.ok(hostAllowed(r.manualUrl,['oppo.com','oppojapan.com']));
 assert.ok(r.noteJa.includes('網羅的な取扱説明書とは限りません'));
 assert.ok(r.noteEn.includes('not necessarily the complete operating manual'));
 const u=new URL(aff.buildModelSearchUrl(r));
 assert.equal(u.hostname,'www.amazon.co.jp');
 assert.equal(u.searchParams.get('tag'),'nicheworks09-22');
 assert.equal(u.searchParams.get('k'),'OPPO '+r.model);
 assert.equal(aff.getConsumableOffers(r).length,0);
}
assert.equal(rows.find(r=>r.model==='Reno13 A').manualKind,'direct-quick-guide-pdf');
assert.ok(rows.find(r=>r.model==='Reno3 5G').noteJa.includes('ソフトバンク'));
assert.equal(rows.filter(r=>r.manualKind==='direct-getting-started-guide-pdf').length,6);
const cov=fs.readFileSync(new URL('COVERAGE.md',root),'utf8');
assert.ok(cov.includes('**2,679 verified model/caliber rows**'));
assert.ok(cov.includes('| **Total** | **2,679** |'));
assert.ok(cov.includes('| OPPO | 7 | expanded, bounded |'));
assert.ok(cov.includes('| 23 | OPPO | **expanded — 7**'));
for(const f of ['index.html','en/index.html','app.paged.js'])assert.ok(fs.readFileSync(new URL(f,root),'utf8').includes('mf-oneplus12-20261106a'),f);
console.log('OPPO 7 Japanese PDF source-validated model guides, 2 held, 7 precise affiliate model searches PASS');
