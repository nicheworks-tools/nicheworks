import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {validateCoveragePass,hostAllowed} from '../scripts/coverage-pass-lib.mjs';
const root=new URL('../',import.meta.url);
const manifest=JSON.parse(fs.readFileSync(new URL('coverage-passes/oneplus/global-english-twelve-20261106.json',root),'utf8'));
const gate=validateCoveragePass(manifest);
assert.equal(gate.valid,true,gate.errors.join('; '));
assert.equal(gate.completionReady,true);
assert.equal(manifest.status,'coverage-pass-complete');
assert.equal(gate.summary.capturedPopulation,12);
assert.equal(gate.summary.unreviewedCount,0);
assert.deepEqual(gate.summary.states,{direct:12,shared:0,support_only:0,held:0});
assert.deepEqual(manifest.reconciliation,{captured:12,direct:12,shared:0,support_only:0,held:0,public:12});
assert.equal(manifest.published,12);
assert.equal(manifest.universe.sourceObservation.liveRunId,42168500772);
assert.equal(new Set(manifest.universe.sourceUrls).size,12);
assert.equal(new Set(manifest.universe.models).size,12);
const ctx=vm.createContext({window:{},URL});
for(const f of ['data/manuals.coverage-passes.js','data/manuals.coverage-pass.oneplus-global-en-twelve.js','affiliate-config.js'])vm.runInContext(fs.readFileSync(new URL(f,root),'utf8'),ctx,{filename:f});
assert.ok(Array.from(ctx.window.MANUALFINDER_COVERAGE_PASS_BATCHES).includes('manuals.coverage-pass.oneplus-global-en-twelve.js'));
const rows=Array.from(ctx.window.MANUALFINDER_BUILD_COVERAGE_PASSES()).filter(x=>x.maker==='OnePlus');
assert.equal(rows.length,12);
assert.equal(new Set(rows.map(x=>x.model)).size,12);
assert.equal(new Set(rows.map(x=>x.manualUrl)).size,12);
assert.deepEqual(new Set(rows.map(x=>x.model)),new Set(manifest.universe.models));
const evidence=new Map(manifest.records.map(x=>[x.model,x]));
const cfg=ctx.window.MANUALFINDER_AFFILIATE_CONFIG;
for(const row of rows){
 const proof=evidence.get(row.model);
 assert.ok(proof,row.model);
 assert.equal(proof.state,'direct');
 assert.equal(row.brand,'OnePlus');
 assert.equal(row.category,'PC・スマホ');
 assert.equal(row.sourceType,'official');
 assert.equal(row.sourceLevel,'A');
 assert.equal(row.verifiedAt,'2026-11-06');
 assert.equal(row.manualUrl,proof.manualUrl);
 assert.equal(row.evidenceUrl,proof.manualUrl);
 assert.equal(row.supportUrl,proof.supportUrl);
 assert.equal(row.sharedTarget,false);
 assert.equal(row.resolutionState,'direct_manual_page');
 assert.equal(row.manualKind,proof.manualKind);
 assert.ok(hostAllowed(row.manualUrl,['oneplus.com']));
 assert.ok(row.linkReview.includes('42168500772'));
 const isQuick=proof.documentType==='quick';
 if(isQuick){
  assert.equal(row.country,'Europe');
  assert.equal(row.manualKind,'direct-quick-guide-pdf');
  assert.ok(row.noteJa.includes('英語版EU向け'));
  assert.ok(row.noteJa.includes('詳細な取扱説明書ではなく'));
  assert.ok(row.noteEn.includes('NOT a full user manual'));
  assert.ok(row.aliases.includes(proof.printedCode));
 }else{
  assert.equal(row.country,'Global');
  assert.equal(row.manualKind,'direct-full-user-manual-pdf');
  assert.ok(row.noteJa.includes('英語版ユーザーマニュアル'));
  assert.ok(row.noteEn.includes('full user manual'));
 }
 const link=new URL(cfg.buildModelSearchUrl(row));
 assert.equal(link.hostname,'www.amazon.co.jp');
 assert.equal(link.searchParams.get('tag'),'nicheworks09-22');
 assert.equal(link.searchParams.get('k'),'OnePlus '+row.model);
 assert.equal(cfg.getConsumableOffers(row).length,0,'No unverified batteries/chargers');
}
assert.equal(rows.filter(x=>x.manualKind==='direct-full-user-manual-pdf').length,8);
assert.equal(rows.filter(x=>x.manualKind==='direct-quick-guide-pdf').length,4);
const cov=fs.readFileSync(new URL('COVERAGE.md',root),'utf8');
assert.ok(cov.includes('**2,685 verified model/caliber rows**'));
assert.ok(cov.includes('| **Total** | **2,685** |'));
assert.ok(cov.includes('| OnePlus | 12 | expanded, bounded |'));
assert.ok(cov.includes('| 24 | OnePlus | **expanded — 12**'));
for(const f of ['index.html','en/index.html','app.paged.js'])assert.ok(fs.readFileSync(new URL(f,root),'utf8').includes('mf-dyson6-20261106a'),f);
console.log('OnePlus 12 real manufacturer PDFs = 8 full English + 4 EU English quick guides, canonical model searches and prior counts reconciled PASS');
