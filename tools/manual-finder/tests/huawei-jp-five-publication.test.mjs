import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {validateCoveragePass,hostAllowed} from '../scripts/coverage-pass-lib.mjs';
const root=new URL('../',import.meta.url);
const pass=JSON.parse(fs.readFileSync(new URL('coverage-passes/huawei/jp-wearables-five-user-guides-20261104.json',root),'utf8'));
const val=validateCoveragePass(pass);
assert.equal(val.valid,true,val.errors.join('; '));
assert.equal(val.completionReady,true);
assert.equal(pass.status,'coverage-pass-complete');
assert.equal(val.summary.capturedPopulation,5);
assert.equal(val.summary.unreviewedCount,0);
assert.deepEqual(val.summary.states,{direct:5,shared:0,support_only:0,held:0});
assert.deepEqual(pass.reconciliation,{captured:5,direct:5,shared:0,support_only:0,held:0,public:5});
assert.equal(new Set(pass.universe.models).size,5);
assert.equal(new Set(pass.universe.sourceUrls).size,5);
assert.ok(pass.universe.sourceObservation.manufacturerHowTo.endsWith('/ja-jp00753143/'));
const ctx=vm.createContext({window:{},URL});
for(const f of ['data/manuals.coverage-passes.js','data/manuals.coverage-pass.huawei-jp-wearables-5.js','affiliate-config.js'])vm.runInContext(fs.readFileSync(new URL(f,root),'utf8'),ctx,{filename:f});
assert.ok(Array.from(ctx.window.MANUALFINDER_COVERAGE_PASS_BATCHES).includes('manuals.coverage-pass.huawei-jp-wearables-5.js'));
const rows=Array.from(ctx.window.MANUALFINDER_BUILD_COVERAGE_PASSES()).filter(x=>x.maker==='Huawei');
assert.equal(rows.length,5);
assert.equal(new Set(rows.map(x=>x.id)).size,5);
assert.deepEqual(new Set(rows.map(x=>x.model)),new Set(pass.universe.models));
const evidence=new Map(pass.records.map(x=>[x.model,x]));
const affiliate=ctx.window.MANUALFINDER_AFFILIATE_CONFIG;
for(const row of rows){
 const proof=evidence.get(row.model);
 assert.ok(proof,row.model);
 assert.equal(proof.state,'direct');
 assert.equal(row.manualUrl,proof.manualUrl);
 assert.equal(row.supportUrl,proof.supportUrl);
 assert.equal(row.evidenceUrl,pass.universe.sourceObservation.manufacturerHowTo);
 assert.equal(row.manualKind,'manual-index');
 assert.equal(row.resolutionState,'direct_manual_page');
 assert.equal(row.sharedTarget,false);
 assert.equal(row.brand,'Huawei');
 assert.equal(row.category,'その他');
 assert.equal(row.country,'Japan');
 assert.equal(row.sourceType,'official');
 assert.equal(row.sourceLevel,'A');
 assert.equal(row.verifiedAt,'2026-11-04');
 assert.ok(hostAllowed(row.manualUrl,['huawei.com']));
 assert.equal(new URL(row.manualUrl).hostname,'consumer.huawei.com');
 assert.match(new URL(row.manualUrl).pathname,/^\/jp\/support\/wearables\/[a-z0-9-]+\/$/);
 assert.ok(row.noteJa.includes('ユーザーガイド'));
 assert.ok(row.noteJa.includes('直接リンクではありません'));
 assert.ok(row.evidenceUrl.includes('ja-jp00753143'));
 assert.ok(row.linkReview.includes(row.manualUrl));
 assert.equal(affiliate.buildModelSearchUrl(row),'','unapproved その他 wearable category must not leak Amazon tagged links');
 assert.equal(affiliate.getConsumableOffers(row).length,0);
}
const coverage=fs.readFileSync(new URL('COVERAGE.md',root),'utf8');
assert.ok(coverage.includes('**2,679 verified model/caliber rows**'));
assert.ok(coverage.includes('| **Total** | **2,679** |'));
assert.ok(coverage.includes('| Huawei | 5 | expanded, bounded |'));
assert.ok(coverage.includes('| 21 | Huawei | **expanded — 5**'));
for(const f of ['index.html','en/index.html','app.paged.js'])assert.ok(fs.readFileSync(new URL(f,root),'utf8').includes('mf-oneplus12-20261106a'),f);
console.log('Huawei JP official FAQ table 5 manual download indexes, exact product pages, no unsupported direct PDF and no unauthorized affiliate category, runtime PASS.');
