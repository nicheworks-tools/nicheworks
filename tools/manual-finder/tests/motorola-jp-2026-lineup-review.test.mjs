import assert from 'node:assert/strict';
import fs from 'node:fs';
import {validateCoveragePass} from '../scripts/coverage-pass-lib.mjs';
import {extractPopulation,checkManualHtml,reviewAll} from '../scripts/motorola-jp-lineup-review.mjs';
const pass=JSON.parse(fs.readFileSync(new URL('../coverage-passes/motorola/jp-motobu-2026-smartphone-lineup.json',import.meta.url),'utf8'));
const v=validateCoveragePass(pass);assert.equal(v.valid,true,v.errors.join('; '));
assert.equal(pass.universe.models.length,12);
const fake='<h2>Products Lineup</h2>'+pass.universe.models.concat(['moto pen ultra']).map(model=>'<h4><img alt="'+model+'" src="/assets/logo.webp"></h4>').join('');
assert.deepEqual(extractPopulation(fake,pass),pass.universe.models);
assert.throws(()=>extractPopulation(fake.replace('motorola razr fold','motorola razr fold pro'),pass),/changed/);
assert.throws(()=>extractPopulation(fake.replace('<h4><img alt="moto pen ultra" src="/assets/logo.webp"></h4>',''),pass),/boundary changed/);
const guide=(name,mode='help')=>mode==='help'?{url:'https://help.motorola.com/hc/1234/16/global/en-us/index.html?t=index',html:'<title>'+name+'</title><main>Getting started Home screen Settings '+('Operating your phone. ').repeat(1400)+'</main>'}:{url:'https://jp-jp.support.motorola.com/app/answers/detail/a_id/12345/',html:'<title>'+name+' - ユーザーガイド(HTML)</title><p>デバイスを使用する方法 ユーザーガイド</p>'};
assert.equal(checkManualHtml(guide('motorola edge 60'),'motorola edge 60').accepted,true);
assert.equal(checkManualHtml(guide('motorola edge 60 pro'),'motorola edge 60').accepted,false);
assert.equal(checkManualHtml(guide('motorola edge 60'),'motorola edge 60 pro').accepted,false);
assert.equal(checkManualHtml(guide('moto g37'),'moto g 37 j').accepted,false);
assert.equal(checkManualHtml(guide('moto g37j','region'),'moto g 37 j',{alias:'moto g37j',regional:true}).accepted,true);
const reviewed=await reviewAll({pass,indexHtml:fake,fetcher:async url=>{
 if(url.includes('a_id/192333/'))return guide('moto g37j','region');
 if(url.includes('a_id/187425/'))return guide('moto g66j 5G','region');
 const model=new URL(url).searchParams.get('m');
 return guide(model);
}});
assert.equal(reviewed.officialPhonePopulation,12);
assert.deepEqual(reviewed.counts,{direct:12,shared:0,support_only:0,held:0});
assert.equal(new Set(reviewed.records.map(x=>x.manualUrl)).size,12);
const negative=await reviewAll({pass,indexHtml:fake,fetcher:async url=>guide('not this model')});
assert.equal(negative.counts.held,12);
console.log('Motorola JP 12-model official population, device guide exact identity and fail-closed tests passed.');
