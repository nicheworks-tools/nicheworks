import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {validateCoveragePass,hostAllowed} from '../scripts/coverage-pass-lib.mjs';
const root=new URL('../',import.meta.url);
const pass=JSON.parse(fs.readFileSync(new URL('coverage-passes/msi/jp-ms1542-gp-ge-manual-20261104.json',root),'utf8'));
const gate=validateCoveragePass(pass);
assert.equal(gate.valid,true,gate.errors.join('; '));
assert.equal(gate.completionReady,true);
assert.equal(pass.status,'coverage-pass-complete');
assert.equal(gate.summary.capturedPopulation,6);
assert.equal(gate.summary.unreviewedCount,0);
assert.deepEqual(gate.summary.states,{direct:0,shared:6,support_only:0,held:0});
assert.deepEqual(pass.reconciliation,{captured:6,direct:0,shared:6,support_only:0,held:0,public:6});
assert.equal(pass.universe.sourceObservation.liveRunId,41801269196);
assert.equal(pass.universe.sourceObservation.bytesValidated,true);
assert.equal(new Set(pass.universe.models).size,6);
assert.equal(pass.groups.length,2);
const ctx=vm.createContext({window:{},URL});
for(const p of ['data/manuals.coverage-passes.js','data/manuals.coverage-pass.msi-jp-ms1542-six.js','affiliate-config.js'])vm.runInContext(fs.readFileSync(new URL(p,root),'utf8'),ctx,{filename:p});
assert.ok(Array.from(ctx.window.MANUALFINDER_COVERAGE_PASS_BATCHES).includes('manuals.coverage-pass.msi-jp-ms1542-six.js'));
const rows=Array.from(ctx.window.MANUALFINDER_BUILD_COVERAGE_PASSES()).filter(x=>x.maker==='MSI');
assert.equal(rows.length,6);
assert.equal(new Set(rows.map(x=>x.manualUrl)).size,2);
assert.equal(new Set(rows.map(x=>x.model)).size,6);
assert.equal(new Set(rows.map(x=>x.id)).size,6);
assert.deepEqual(new Set(rows.map(x=>x.model)),new Set(pass.universe.models));
const evidence=new Map(pass.records.map(x=>[x.model,x]));
const affiliate=ctx.window.MANUALFINDER_AFFILIATE_CONFIG;
for(const row of rows){
 const e=evidence.get(row.model);
 assert.ok(e);
 assert.equal(e.state,'shared');
 assert.equal(e.platform,'MS-1542');
 assert.equal(row.brand,'MSI');
 assert.equal(row.category,'PC・スマホ');
 assert.equal(row.country,'Japan');
 assert.equal(row.sourceType,'official');
 assert.equal(row.sourceLevel,'A');
 assert.equal(row.manualUrl,e.manualUrl);
 assert.equal(row.supportUrl,e.manualUrl);
 assert.equal(row.evidenceUrl,pass.manufacturerOfficialMappingUrl);
 assert.equal(row.sharedTarget,true);
 assert.equal(row.manualKind,'shared-user-guide-pdf');
 assert.equal(row.resolutionState,'shared_manual_page');
 assert.equal(row.verifiedAt,'2026-11-04');
 assert.ok(row.noteJa.includes('内部型番はMS-1542'));
 assert.ok(row.noteEn.includes('configuration-dependent'));
 assert.ok(hostAllowed(row.manualUrl,pass.allowedDomains));
 const u=new URL(row.manualUrl);
 assert.equal(u.hostname,'download.msi.com');
 assert.match(u.pathname,/^\/archive\/mnu_exe\/nb\/MS-1542_v1\.0_Japanese_(GP|GE)\.pdf$/);
 const a=new URL(affiliate.buildModelSearchUrl(row));
 assert.equal(a.hostname,'www.amazon.co.jp');
 assert.equal(a.searchParams.get('tag'),'nicheworks09-22');
 assert.equal(a.searchParams.get('k'),'MSI '+row.model);
 assert.equal(affiliate.getConsumableOffers(row).length,0,'no unverified battery, adapter or hardware fit offers');
}
assert.deepEqual(rows.filter(x=>x.model.startsWith('GP66')).map(x=>x.manualUrl).every(x=>x.endsWith('_GP.pdf')),true);
assert.deepEqual(rows.filter(x=>x.model.startsWith('GE66')).map(x=>x.manualUrl).every(x=>x.endsWith('_GE.pdf')),true);
assert.ok(!rows.some(x=>x.model.includes('GE65')));
const cov=fs.readFileSync(new URL('COVERAGE.md',root),'utf8');
assert.ok(cov.includes('**2,655 verified model/caliber rows**'));
assert.ok(cov.includes('| **Total** | **2,655** |'));
assert.ok(cov.includes('| MSI | 6 | expanded, bounded |'));
assert.ok(cov.includes('| 14 | MSI | **expanded — 6**'));
for(const f of ['index.html','en/index.html','app.paged.js'])assert.ok(fs.readFileSync(new URL(f,root),'utf8').includes('mf-msi6-20261104a'),f);
console.log('MSI JP 2 Japanese PDF / 6 exact manufacturer-platform mapped variants (all 6 shared), no inferred parts; bilingual runtime and affiliate PASS.');
