import assert from 'node:assert/strict';
import vm from 'node:vm';
import fs from 'node:fs';
const source=fs.readFileSync('assets/okj-name-place-batch.js','utf8');
const sandbox=vm.createContext({window:{}});
vm.runInContext(source,sandbox);
const batch=sandbox.window.OldKanjiNamePlaceBatch;
const nameGate={active:true,productId:'okj.toolkit_pro',featureId:'okj.name.batch'};
const placeGate={active:true,productId:'okj.toolkit_pro',featureId:'okj.place.batch'};
const dict=JSON.parse(fs.readFileSync('tools/old-kanji-reference/dict.json','utf8'));
assert.equal(batch.parseLines(' 齋藤\n\n渡邊\r\n濱田').rows.length,3);
assert.equal(batch.parseLines(Array(201).fill('A').join('\n')).error,'too_many_rows');
assert.equal(batch.parseLines('x'.repeat(401)).error,'row_too_long');
const csv=batch.parseCsv('\uFEFF氏名,メモ\r\n"齋藤, 太郎","A, B"\r\n渡邊,test', 'name');
assert.equal(csv.ok,true);
assert.deepEqual(Array.from(csv.rows),['齋藤, 太郎','渡邊']);
assert.equal(batch.parseCsv('name\n"未閉鎖','name').error,'invalid_csv');
assert.equal(batch.parseCsv('A,B\nC,D','name').error,'select_column');
assert.equal(batch.parseCsv('住所,備考\n"廣島市, 〇〇",x\n國府,y','place').rows.length,2);
const wrong={active:true,productId:'okj.toolkit_pro',featureId:'okj.workspaces'};
assert.equal(batch.analyzeRows(['齋藤'],dict,wrong,'name').error,'pro_required');
assert.equal(batch.analyzeRows(['齋藤'],dict,placeGate,'name').error,'pro_required');
assert.equal(batch.analyzeRows(['廣島'],dict,nameGate,'place').error,'pro_required');
const names=batch.analyzeRows(['齋藤','渡邊','普通名'],dict,nameGate,'name');
assert.equal(names.ok,true);
assert.equal(names.count,3);
assert.ok(names.matched>=2);
assert.ok(names.rows[0].matches.some(m=>m.relationship==='old_to_modern'));
assert.ok(names.rows[1].matches.some(m=>m.modernCandidates.includes('辺')));
assert.equal(names.rows[2].status,'no_reference_match');
const places=batch.analyzeRows(['廣島','国府'],dict,placeGate,'place');
assert.equal(places.ok,true);
assert.ok(places.rows[0].matches.some(m=>m.modernCandidates.includes('広')));
assert.ok(places.rows[1].matches.some(m=>m.relationship==='modern_to_old'));
assert.equal(batch.exportCsv(names,wrong).error,'pro_required');
const exported=batch.exportCsv(names,nameGate);
assert.equal(exported.ok,true);
assert.ok(exported.content.startsWith('\uFEFF'));
assert.ok(exported.content.includes('齋藤'));
const dangerous=batch.analyzeRows(['=IMPORTXML("https://example.com")'],dict,nameGate,'name');
assert.ok(batch.exportCsv(dangerous,nameGate).content.includes('"\'=IMPORTXML'));
const json=JSON.parse(batch.exportJson(places,placeGate).content);
assert.equal(json.rows.length,2);
assert.equal(batch.exportJson(places,nameGate).error,'pro_required');
for(const slug of ['name-old-kanji-checker','place-old-kanji-checker']){
 const html=fs.readFileSync('tools/'+slug+'/index.html','utf8');
 assert.ok(html.includes('/assets/okj-name-place-batch.js'),slug+' engine include');
 assert.ok(html.includes('/assets/okj-name-place-batch-ui.js'),slug+' UI include');
}
const ui=fs.readFileSync('assets/okj-name-place-batch-ui.js','utf8');
assert.ok(ui.includes("refreshProState({productId:PRODUCT,featureId:feature})"));
assert.ok(ui.includes("batch.analyzeRows("));
assert.doesNotMatch(ui,/gtag\(|amazon\.co\.jp|api\/billing\/create-checkout-session/);
console.log('Name/place batch: real dictionary matching, CSV import/export, formula escape, feature gates PASS');
