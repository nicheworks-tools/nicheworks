import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { runInNewContext } from "node:vm";
import { test } from "node:test";
const source = readFileSync(new URL("../tools/command-safety-checker/app-core.js", import.meta.url), "utf8");
test("production checker invalidates stale reports and rejects failed clipboard fallback", async () => {
  const elements = new Map();
  const make = () => ({ value:"", hidden:true, textContent:"", innerHTML:"", style:{}, dataset:{}, listeners:{}, classList:{toggle(){}}, appendChild(){}, removeChild(){}, select(){}, focus(){}, addEventListener(n,f){this.listeners[n]=f;} });
  const get = id => {if(!elements.has(id)) elements.set(id,make());return elements.get(id);};
  const document = { getElementById:get, querySelectorAll(){return []}, addEventListener(n,f){this.listeners[n]=f;}, listeners:{}, createElement:make, body:{appendChild(){},removeChild(){}}, execCommand(){return false;} };
  const navigator = {language:"en",clipboard:{async writeText(){throw Error("blocked")}}};
  const window = {};
  runInNewContext(source,{document,navigator,window,setTimeout(){return 1},clearTimeout(){},console});
  get("cmdInput").value="rm -rf /";
  get("analyzeBtn").listeners.click();
  assert.ok(window.__cscLastResult);
  assert.equal(get("resultSection").hidden,false);
  get("cmdInput").value="echo safe";
  get("cmdInput").listeners.input();
  assert.equal(window.__cscLastResult,null);
  assert.equal(get("resultSection").hidden,true);
  get("analyzeBtn").listeners.click();
  assert.ok(window.__cscLastResult);
  get("osSelect").value="powershell";
  get("osSelect").listeners.change();
  assert.equal(window.__cscLastResult,null);
  get("cmdInput").value="rm -rf /";
  get("analyzeBtn").listeners.click();
  get("cmdInput").value="   ";
  get("analyzeBtn").listeners.click();
  assert.equal(window.__cscLastResult,null);
  get("cmdInput").value="rm -rf /";
  get("analyzeBtn").listeners.click();
  await get("copyBtn").listeners.click();
  assert.equal(get("toast").textContent,"Copy failed");
  document.listeners.click({target:{closest(){return {dataset:{preset:"echo new",os:"unix"}}}}});
  assert.equal(window.__cscLastResult,null);
});
